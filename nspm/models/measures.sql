    CAST(measure_annual_o_m_cost_per_unit_doller_per_year AS FLOAT) AS measure_annual_o_m_cost_per_unit_doller_per_year,
    CAST(measure_one_time_incentive_utility_per_unit_doller_per_year AS FLOAT) AS measure_one_time_incentive_utility_per_unit_doller_per_year,
    CAST(measure_annual_incentive_utility_per_unit_doller_per_year AS FLOAT) AS measure_annual_incentive_utility_per_unit_doller_per_year,
    CAST(administration_costs_doller_per_year AS FLOAT) AS administration_costs_doller_per_year,
    CAST(measure_transaction_costs_per_unit_doller_per_year AS FLOAT) AS measure_transaction_costs_per_unit_doller_per_year,
    CAST(measure_interconnection_costs_per_unit_doller_per_year AS FLOAT) AS measure_interconnection_costs_per_unit_doller_per_year,
    CAST(measure_tax_incentives_per_unit_doller_per_year AS FLOAT) AS measure_tax_incentives_per_unit_doller_per_year,
    CAST(measure_non_energy_impacts_per_unit_doller_per_year AS FLOAT) AS measure_non_energy_impacts_per_unit_doller_per_year,      
    CAST(measure_non_energy_impacts_low_income_per_unit_doller_per_year AS FLOAT) AS measure_non_energy_impacts_low_income_per_unit_doller_per_year,
    CAST(change_in_host_customer_reliability_customer_minute_outages_cmo AS FLOAT)
        AS change_in_host_customer_reliability_customer_minute_outages_cmo,
    CAST(custom_1_subsector AS STRING) AS custom_1_subsector,
    CAST(custom_2_zip_code AS STRING) AS custom_2_zip_code, 
    CAST(custom_3 AS STRING) AS custom_3,
    CAST(custom_4 AS STRING) AS custom_4,
    CAST(custom_5 AS STRING) AS custom_5
FROM nspm.openbca_input_measures