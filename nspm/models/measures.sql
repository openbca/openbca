    name openbca_input.measures,
    kind FULL,
    grain(
        unique_row_id,
        measure_id, 
        project_id, 
        program_name, 
        measure_include, 
        version, 
        subset, 
        start_year, 
        start_quarter, 
        measure_name, 
        measure_unit, 
        unit_quantity, 
        loadshape_mapping, 
        annual_kwh_impact, 
        peak_kw_impact, 
        annual_ng_impact_mmbtu, 
        annual_other_fuels_impact_mmbtu, 
        estimated_useful_life_years, 
        ntg, 
        measure_incremental_costs_per_unit_doller, 
        measure_annual_o_m_cost_per_unit_doller_per_year, 
